public static string Wrap(string text,float width,int size,bool bold=false) {
 var lines=new List<string>();width=Math.Max(1,width);
 foreach(var paragraph in (text??" ").Replace("\r","").Split('\n')) {
  string line="";
  foreach(var word in paragraph.Split(new[]{' '},StringSplitOptions.RemoveEmptyEntries)) {
   string candidate=line.Length==0?word:line+" "+word;
   if(Measure(candidate,size,bold)<=width){line=candidate;continue;}
   if(line.Length>0){lines.Add(line);line="";}
   // A long translated compound word is split safely instead of leaving the panel.
   foreach(char c in word){if(line.Length>0&&Measure(line+c,size,bold)>width){lines.Add(line);line="";}line+=c;}
  }
  lines.Add(line);
 }
 return string.Join("\n",lines);
}
